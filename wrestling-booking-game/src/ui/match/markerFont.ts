/** What the marker can write: capitals, accents dropped, anything unknown left out. */
export function markerText(text: string): string {
  return [...text.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase().replace(/[‘’]/g, "'")]
    .filter((c) => c in MARKER)
    .join('')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Letter spacing, as a share of the letter height. */
export const MARKER_GAP = 0.2;

/** How wide a line comes out, in letter heights. */
export function markerWidth(text: string): number {
  const t = markerText(text);
  return [...t].reduce((n, c) => n + MARKER[c]!.w, 0) + Math.max(0, t.length - 1) * MARKER_GAP;
}

/**
 * The line as one SVG path `d`, centred on `cx`, sitting on `baseY`, letters
 * `h` tall. `rnd` supplies the wobble: each letter rides up or down and
 * leans a bit, and every point of every stroke lands a little off.
 */
export function markerPath(text: string, cx: number, baseY: number, h: number, rnd: () => number): string {
  const t = markerText(text);
  let x = cx - (markerWidth(t) * h) / 2;
  const parts: string[] = [];
  for (const c of t) {
    const g = MARKER[c]!;
    const s = h * (0.92 + rnd() * 0.16);
    const lift = (rnd() - 0.5) * h * 0.14;
    const lean = (rnd() - 0.5) * 0.22;
    const top = baseY - s + lift;
    for (const stroke of g.s) {
      const p = stroke.map(([u, v]) => {
        const px = x + u * s + (1 - v) * lean * s * 0.5 + (rnd() - 0.5) * h * 0.06;
        const py = top + v * s + (rnd() - 0.5) * h * 0.06;
        return `${px.toFixed(1)},${py.toFixed(1)}`;
      });
      parts.push(`M ${p.join(' L ')}`);
    }
    x += (g.w + MARKER_GAP) * h;
  }
  return parts.join(' ');
}
