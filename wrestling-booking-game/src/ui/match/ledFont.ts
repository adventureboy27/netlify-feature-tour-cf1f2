export const GLYPH_W = 5;
export const GLYPH_H = 7;

const parsed = new Map<string, boolean[][]>(
  Object.entries(G).map(([ch, rows]) => [ch, rows.split('|').map((r) => [...r].map((c) => c === '#'))]),
);

/** What the sign can spell: capitals, accents dropped, anything else a space. */
export function signText(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .replace(/[‘’]/g, "'")
    .split('')
    .map((c) => (parsed.has(c) ? c : ' '))
    .join('')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * The text as columns of lit bulbs, `scale` bulbs per font dot, one dot of
 * space between letters. `cols[x][y]` is lit.
 */
export function bitmap(text: string, scale: number): boolean[][] {
  const cols: boolean[][] = [];
  const t = signText(text);
  for (let i = 0; i < t.length; i++) {
    const g = parsed.get(t[i]!)!;
    for (let gx = 0; gx < GLYPH_W; gx++) {
      const col: boolean[] = [];
      for (let gy = 0; gy < GLYPH_H; gy++) for (let s = 0; s < scale; s++) col.push(g[gy]![gx]!);
      for (let s = 0; s < scale; s++) cols.push(col);
    }
    if (i < t.length - 1) for (let s = 0; s < scale; s++) cols.push(new Array(GLYPH_H * scale).fill(false));
  }
  return cols;
}
